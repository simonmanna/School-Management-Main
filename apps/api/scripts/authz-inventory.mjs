#!/usr/bin/env node
/**
 * Authorization-boundary inventory (audit 2026-09-27, plan Phase 1.1).
 *
 * Lists every school route that names a pupil or a class, the permissions it
 * demands, and how pupil/class scope is enforced:
 *   - pupil-keyed routes: the global PupilScopeGuard (unless @PupilScopeExempt)
 *     or a portal @ScopedToStudent;
 *   - class-keyed routes: a DataScopeService class assertion or seat filter
 *     reachable from the handler's service call, or a school-wide-only grant.
 *
 * Writes docs/audit/authz-inventory.md. `--check` exits non-zero when a
 * class-keyed route readable by a teacher grant has no recognised enforcement.
 */
import { readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';

const root = new URL('..', import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1');
const repo = join(root, '..', '..');
const schoolDir = join(root, 'src', 'modules', 'school');

/** Grants held by the Class Teacher / Subject Teacher presets (restricted scope). */
const shared = readFileSync(join(repo, 'packages', 'shared', 'src', 'permissions.ts'), 'utf8');
const teacherGrants = new Set();
for (const name of ['Class Teacher', 'Subject Teacher']) {
  const i = shared.indexOf(`name: '${name}'`);
  const block = shared.slice(i, shared.indexOf(']', shared.indexOf('permissions: [', i)));
  for (const m of block.matchAll(/'([a-z_]+:[a-z_:]+)'/g)) teacherGrants.add(m[1]);
}
/** PERMISSIONS.school.x -> 'school:...' */
const permValue = new Map();
for (const m of shared.matchAll(/^\s{4}(\w+): '([a-z_]+:[a-z_:]+)',/gm)) permValue.set(m[1], m[2]);

const walk = (d) => readdirSync(d).flatMap((f) => {
  const p = join(d, f);
  return statSync(p).isDirectory() ? walk(p) : p.endsWith('.controller.ts') ? [p] : [];
});

/** Class-keyed routes that return no pupil data, with the reason. Reviewed by hand. */
const NON_PUPIL = new Map([
  ['GET /school/lms/courses', 'course catalogue filtered by class; no learner rows'],
]);

const SCOPE_CALL = /assertMayRead(Student|Class)|assertMayTouch(Class|Student)|assertTeachesClass|studentReadWhere|visibleStudentIds|readableSeats|readableClassIds|assertSchoolWide|ScopedToClass|ScopedToStudent/;

const rows = [];
for (const file of walk(schoolDir)) {
  const src = readFileSync(file, 'utf8');
  const base = (src.match(/@Controller\('([^']*)'\)/) ?? [])[1] ?? '';
  const serviceFiles = [...src.matchAll(/from '(\.[^']+\.service)'/g)].map((m) => join(file, '..', m[1] + '.ts'));
  const services = serviceFiles.map((f) => { try { return readFileSync(f, 'utf8'); } catch { return ''; } }).join('\n');
  const re = /@(Get|Post|Patch|Put|Delete)\(([^)]*)\)([\s\S]*?)\n\s{2}(?:async\s+)?(\w+)\(([\s\S]*?)\)\s*(?::[^{]+)?\{([\s\S]*?)\n\s{2}\}/g;
  for (const m of src.matchAll(re)) {
    const [, verb, pathArg, decorators, handler, params, body] = m;
    const path = `/${base}/${(pathArg.match(/'([^']*)'/) ?? [])[1] ?? ''}`.replace(/\/+/g, '/').replace(/\/$/, '');
    const pupil = /studentProfileId|studentId|studentProfileIds/.test(params + pathArg);
    const klass = /classId/.test(params + pathArg);
    if (!pupil && !klass) continue;
    const perms = [...decorators.matchAll(/PERMISSIONS\.school\.(\w+)|P\.(\w+)/g)].map((x) => permValue.get(x[1] ?? x[2]) ?? x[1] ?? x[2]);
    const teacherReadable = perms.length > 0 && perms.every((p) => teacherGrants.has(p));
    const exempt = /PupilScopeExempt/.test(decorators);
    const called = [...body.matchAll(/\.(\w+)\(/g)].map((x) => x[1]);
    const methodScoped = called.some((name) => {
      const i = services.indexOf(`async ${name}(`) >= 0 ? services.indexOf(`async ${name}(`) : services.indexOf(` ${name}(`);
      return i >= 0 && SCOPE_CALL.test(services.slice(i, i + 4000));
    });
    const inline = SCOPE_CALL.test(decorators + body);
    let enforcement;
    if (pupil && !exempt) enforcement = 'PupilScopeGuard';
    else if (inline || methodScoped) enforcement = 'DataScopeService (service)';
    else if (!teacherReadable) enforcement = 'school-wide grant only';
    else if (NON_PUPIL.has(`${verb.toUpperCase()} ${path}`)) enforcement = `not pupil data: ${NON_PUPIL.get(`${verb.toUpperCase()} ${path}`)}`;
    else enforcement = '**NONE — review**';
    rows.push({ file: relative(repo, file).replace(/\\/g, '/'), verb, path, handler, perms: perms.join(', ') || '(none)', pupil, klass, teacherReadable, enforcement });
  }
}

rows.sort((a, b) => a.path.localeCompare(b.path) || a.verb.localeCompare(b.verb));
const gaps = rows.filter((r) => r.enforcement.startsWith('**NONE'));
const md = [
  '# Authorization-boundary inventory',
  '',
  'Generated by `apps/api/scripts/authz-inventory.mjs` (audit 2026-09-27, plan Phase 1.1). Re-run after adding a route; `--check` fails CI on a gap.',
  '',
  'Chain for every row: JWT auth → tenant (RLS) → role permission (PermissionsGuard) → **pupil/class scope** → sensitive-record grant → field redaction → write authorization.',
  '',
  '- **PupilScopeGuard**: global guard; any staff request naming a pupil (path, query or body) must name one the caller may read (`DataScopeService.visibleStudentIds`). Portal requests use `@ScopedToStudent`.',
  '- **DataScopeService (service)**: the handler\'s service calls a class/seat assertion or filters by seats.',
  '- **school-wide grant only**: no teacher preset holds the grant, so only school-scope roles reach it.',
  '',
  `Routes: ${rows.length}. Gaps: ${gaps.length}.`,
  '',
  '| Verb | Path | Handler | Grants | Teacher-readable | Scope enforcement | File |',
  '|---|---|---|---|---|---|---|',
  ...rows.map((r) => `| ${r.verb} | \`${r.path}\` | ${r.handler} | ${r.perms} | ${r.teacherReadable ? 'yes' : 'no'} | ${r.enforcement} | ${r.file} |`),
  '',
].join('\n');
writeFileSync(join(repo, 'docs', 'audit', 'authz-inventory.md'), md);
console.log(`routes=${rows.length} gaps=${gaps.length}`);
for (const g of gaps) console.log(`GAP ${g.verb} ${g.path} (${g.handler}) ${g.file}`);
if (process.argv.includes('--check') && gaps.length) process.exit(1);
