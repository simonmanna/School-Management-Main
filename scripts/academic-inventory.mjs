import { mkdir, readFile, readdir, writeFile } from 'node:fs/promises';
import path from 'node:path';

const root = process.cwd();
const schemaPath = path.join(root, 'apps', 'api', 'prisma', 'schema.prisma');
const outDir = path.join(root, 'docs', 'architecture');

const academicTerms = /academic|assessment|grade|mark|result|reportcard|report-card|courseoffering|course-offering|enrollment|enrolment|lesson|exam|homework|lms|curriculum/i;
const writeModels = ['studentAssessment', 'markEntry', 'gradeEntry', 'resultSet', 'reportCard'];

async function walk(dir) {
  const rows = [];
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    if (['dist', 'node_modules', 'coverage', 'migrations', 'migrations-archive', 'superseded-ddl'].includes(entry.name)) continue;
    const absolute = path.join(dir, entry.name);
    if (entry.isDirectory()) rows.push(...await walk(absolute));
    else rows.push(absolute);
  }
  return rows;
}

const rel = (file) => path.relative(root, file).replaceAll('\\', '/');
const lineNo = (text, offset) => text.slice(0, offset).split('\n').length;

async function main() {
  const schema = await readFile(schemaPath, 'utf8');
  const modelNames = [...schema.matchAll(/^model\s+(\w+)\s*\{/gm)].map((m) => m[1]);
  const models = modelNames.filter((name) => academicTerms.test(name));
  const files = [
    ...await walk(path.join(root, 'apps')),
    ...await walk(path.join(root, 'packages')),
    ...await walk(path.join(root, 'scripts')),
  ].filter((f) => /\.(ts|tsx)$/.test(f));

  const endpoints = [];
  const markWrites = [];
  const currentClassReads = [];
  const reportPaths = [];
  const jobs = [];
  const pages = [];

  for (const file of files) {
    const text = await readFile(file, 'utf8');
    const filePath = rel(file);
    if (file.endsWith('.controller.ts') && academicTerms.test(filePath + text.slice(0, 1000))) {
      const base = text.match(/@Controller\(['"`]([^'"`]+)['"`]\)/)?.[1] ?? '';
      const routePattern = /@(Get|Post|Put|Patch|Delete)\((?:['"`]([^'"`]*)['"`])?\)[\s\S]{0,500}?\n\s*(?:async\s+)?(\w+)\s*\(/g;
      for (const match of text.matchAll(routePattern)) {
        endpoints.push({ method: match[1].toUpperCase(), route: `/${base}/${match[2] ?? ''}`.replace(/\/$/, ''), handler: `${filePath}#${match[3]}`, line: lineNo(text, match.index) });
      }
    }

    for (const model of writeModels) {
      const pattern = new RegExp(`\\b(?:tx|this\\.prisma\\.(?:client|raw)|prisma)\\.${model}\\.(create|createMany|update|updateMany|upsert|delete|deleteMany)\\b`, 'g');
      for (const match of text.matchAll(pattern)) markWrites.push({ model, operation: match[1], file: filePath, line: lineNo(text, match.index) });
    }

    for (const match of text.matchAll(/\bcurrentClassId\b/g)) currentClassReads.push({ file: filePath, line: lineNo(text, match.index) });
    if (/reportCard|report-card|ReportCard|ReportDocument|resultSet/i.test(text)) reportPaths.push(filePath);
    if (/@Cron\(|SchedulerRegistry|setInterval\(|worker/i.test(text) && academicTerms.test(filePath + text.slice(0, 1000))) jobs.push(filePath);
    if ((filePath.includes('/pages/') || filePath.includes('/routes/')) && academicTerms.test(filePath)) pages.push(filePath);
  }

  const unique = (items) => [...new Set(items)].sort();
  const groupedClassReads = Object.entries(currentClassReads.reduce((acc, row) => {
    acc[row.file] = (acc[row.file] ?? 0) + 1;
    return acc;
  }, {})).map(([file, occurrences]) => ({ file, occurrences })).sort((a, b) => a.file.localeCompare(b.file));

  const inventory = {
    generatedFrom: 'working-tree',
    scope: ['apps', 'packages', 'scripts', 'apps/api/prisma/schema.prisma'],
    counts: { models: models.length, endpoints: endpoints.length, markWrites: markWrites.length, currentClassFiles: groupedClassReads.length, reportPaths: unique(reportPaths).length, jobs: unique(jobs).length, pages: unique(pages).length },
    models: models.sort(), endpoints, markWrites, currentClassReads: groupedClassReads,
    reportPaths: unique(reportPaths), jobs: unique(jobs), pages: unique(pages),
  };

  const table = (headers, rows) => [
    `| ${headers.join(' | ')} |`,
    `| ${headers.map(() => '---').join(' | ')} |`,
    ...rows.map((row) => `| ${row.map((v) => String(v).replaceAll('|', '\\|')).join(' | ')} |`),
  ].join('\n');

  const markdown = `# Academic Current-State Inventory\n\n` +
    `Generated by \`pnpm academics:inventory\`. This is a discovery artefact, not an approval record. Review diffs whenever academic code changes.\n\n` +
    `## Summary\n\n${table(['Area', 'Count'], Object.entries(inventory.counts).map(([k, v]) => [k, v]))}\n\n` +
    `## Academic models\n\n${models.sort().map((m) => `- \`${m}\``).join('\n')}\n\n` +
    `## HTTP endpoints\n\n${table(['Method', 'Route', 'Handler', 'Line'], endpoints.map((e) => [e.method, `\`${e.route}\``, `\`${e.handler}\``, e.line]))}\n\n` +
    `## Canonical and legacy mark/result writes\n\n${markWrites.length ? table(['Model', 'Operation', 'Location'], markWrites.map((w) => [w.model, w.operation, `\`${w.file}:${w.line}\``])) : '_No statically detectable writes found._'}\n\n` +
    `## \`currentClassId\` consumers\n\n${table(['File', 'Occurrences'], groupedClassReads.map((r) => [`\`${r.file}\``, r.occurrences]))}\n\n` +
    `## Report/result generation and reads\n\n${unique(reportPaths).map((p) => `- \`${p}\``).join('\n')}\n\n` +
    `## Academic jobs and scheduled work\n\n${unique(jobs).map((p) => `- \`${p}\``).join('\n') || '_None detected._'}\n\n` +
    `## Academic pages\n\n${unique(pages).map((p) => `- \`${p}\``).join('\n')}\n\n` +
    `## Review rule\n\nA reviewer must manually check dynamic Prisma access, raw SQL and external integrations. CI fails when this generated snapshot is stale. No newly discovered mark writer may merge without being classified in the Phase 0.5 register.\n`;

  await mkdir(outDir, { recursive: true });
  await writeFile(path.join(outDir, 'academic-current-state-inventory.json'), `${JSON.stringify(inventory, null, 2)}\n`);
  await writeFile(path.join(outDir, 'academic-current-state-inventory.md'), markdown);
  console.log(`Academic inventory: ${inventory.counts.models} models, ${inventory.counts.endpoints} endpoints, ${inventory.counts.markWrites} write sites.`);
}

await main();
